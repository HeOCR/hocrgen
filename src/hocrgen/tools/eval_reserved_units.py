"""Generate hocrgen's ``eval_reserved_units.v1`` registry from heocr-eval's P-mod unit split file (decision 0017).

The registry is never edited by hand. ``sync`` copies the split file verbatim into the package
(``src/hocrgen/data/eval/<name>``) and renders ``src/hocrgen/config/eval_reserved_units.yaml`` from it; ``check``
re-renders the registry from the packaged copy and fails if the committed registry differs (a test runs the same
comparison).

    PYTHONPATH=src python -m hocrgen.tools.eval_reserved_units sync --split <.../labels/pmod_unit_split_vN.json>
    PYTHONPATH=src python -m hocrgen.tools.eval_reserved_units check

Each unit's category is taken straight from the split file: ``eval`` or ``non_eval``. Per-unit annotations (for
example v1's ``status: exposed`` on two non-eval booklets) are not categories and are not carried.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path
from typing import Any, Sequence

import yaml

from hocrgen.config.loader import EVAL_RESERVED_UNITS_FILE, default_config_root, package_root
from hocrgen.config.models import EVAL_RESERVED_UNIT_PREFIXES, EvalReservedUnitsRegistry

PACKAGED_DIR = Path("data") / "eval"
SPLIT_FILE_PATTERN = re.compile(r"^pmod_unit_split_(?P<version>v\d+)\.json$")
UNIT_NAMES = {
    "reshumot_born_digital": "one Reshumot booklet (reshumot:<series>_<booklet number>)",
    "knesset_committee_protocols_pre1976": "one Knesset committee protocol (knesset_protocol:<document id>)",
    "reshumot_scanned": "one scanned Reshumot booklet (reshumot_scanned:<series>_<booklet number>)",
    "knesset_plenary_k1_12": "one Knesset plenary sitting (plenary:K<knesset>_<sitting>)",
    "knesset_plenary_k13_25": "one born-digital Knesset plenary sitting, K13-25 (plenary:K<knesset>_<sitting>)",
    "knesset_committee_protocols_k16plus": "one born-digital Knesset committee session, K16-25 "
                                           "(committee:K<knesset>_<CommitteeSessionID>)",
}
UNASSIGNED_SENTENCE = re.compile(r"[^.]*\bneither list\b[^.]*\.")
HEADER = """\
# GENERATED by `python -m hocrgen.tools.eval_reserved_units sync --split <pmod_unit_split_vN.json>`. Do not edit.
# heocr-engine decision 0017 (heocr-engine#74): heocr-eval owns the printed-modern (P-mod) evaluation set. Units
# listed as eval, and units of these sources in neither list (unassigned), are pinned to the eval_reserved release
# split and refused by every training-input builder (docs/real_source_release_contract.md, section 2).
"""


class SplitFileError(ValueError):
    pass


def split_version(name: str, data: dict[str, Any]) -> str:
    match = SPLIT_FILE_PATTERN.match(name)
    if not match:
        raise SplitFileError(f"split file name {name!r} is not pmod_unit_split_v<N>.json")
    stated = data.get("split_version")
    if stated is not None and stated != match["version"]:
        raise SplitFileError(f"{name} states split_version {stated!r}")
    return match["version"]


def registry_data(split_bytes: bytes, name: str) -> dict[str, Any]:
    """The registry (as plain data) for one split file's bytes and file name. Pure; fails on anything unexpected."""

    data = json.loads(split_bytes.decode("utf-8"))
    if not isinstance(data, dict):
        raise SplitFileError("split file is not a JSON object")
    if data.get("superseded_by"):
        raise SplitFileError(f"{name} is superseded by {data['superseded_by']}; sync the current version")
    version = split_version(name, data)
    for key in ("schema_version", "decision", "owner", "usage"):
        if not isinstance(data.get(key), str) or not data[key].strip():
            raise SplitFileError(f"{name} has no {key}")
    if not str(data["schema_version"]).startswith("heocr_eval_unit_split."):
        raise SplitFileError(f"{name} schema_version {data['schema_version']!r} is not heocr_eval_unit_split.*")
    unassigned = UNASSIGNED_SENTENCE.search(data["usage"])
    if unassigned is None:
        raise SplitFileError(f"{name} usage states no rule for unassigned units")
    sources = []
    for key, value in data.items():
        if not (isinstance(value, dict) and ("eval" in value or "non_eval" in value)):
            continue
        if key not in EVAL_RESERVED_UNIT_PREFIXES:
            raise SplitFileError(f"{name} lists units of {key!r}, which hocrgen does not map; extend the mapping first")
        lists = {}
        for category in ("eval", "non_eval"):
            units = value.get(category)
            if not isinstance(units, list):
                raise SplitFileError(f"{name} {key} has no {category} list")
            ids = [unit.get("unit_id") if isinstance(unit, dict) else None for unit in units]
            if not all(isinstance(unit_id, str) and unit_id for unit_id in ids) or len(ids) != len(set(ids)):
                raise SplitFileError(f"{name} {key} {category} has a missing or repeated unit_id")
            lists[category] = sorted(ids)
        sources.append({"source_id": key, "unit": UNIT_NAMES[key], "eval_units": lists["eval"],
                        "non_eval_units": lists["non_eval"]})
    if not sources:
        raise SplitFileError(f"{name} lists no source units")
    registry = {
        "version": 1,
        "registry_id": "eval_reserved_units.v1",
        "generated_by": "hocrgen.tools.eval_reserved_units sync",
        "split_file": {
            "name": name,
            "split_version": version,
            "schema_version": data["schema_version"],
            "sha256": hashlib.sha256(split_bytes).hexdigest(),
            "packaged_copy": (PACKAGED_DIR / name).as_posix(),
        },
        "decision": data["decision"],
        "owner": data["owner"],
        "usage": data["usage"],
        "unassigned_rule": unassigned.group(0).strip(),
        "reserved_split": "eval_reserved",
        "sources": sorted(sources, key=lambda source: source["source_id"]),
    }
    EvalReservedUnitsRegistry.model_validate(registry)
    return registry


def render_registry(split_bytes: bytes, name: str) -> str:
    return HEADER + yaml.safe_dump(registry_data(split_bytes, name), sort_keys=False, allow_unicode=True, width=120)


def packaged_split_copies(root: Path | None = None) -> list[Path]:
    return sorted(((root or package_root()) / PACKAGED_DIR).glob("pmod_unit_split_v*.json"))


def sync(split: Path, *, package: Path | None = None, config_root: Path | None = None) -> dict[str, Any]:
    package = package or package_root()
    config_root = config_root or default_config_root()
    split_bytes = split.read_bytes()
    text = render_registry(split_bytes, split.name)
    target = package / PACKAGED_DIR / split.name
    target.parent.mkdir(parents=True, exist_ok=True)
    for old in packaged_split_copies(package):
        if old.name != split.name:
            old.unlink()
    target.write_bytes(split_bytes)
    (config_root / EVAL_RESERVED_UNITS_FILE).write_text(text, encoding="utf-8")
    registry = yaml.safe_load(text)
    return {"split_file": registry["split_file"],
            "units": {source["source_id"]: {"eval": len(source["eval_units"]), "non_eval": len(source["non_eval_units"])}
                      for source in registry["sources"]}}


def check(*, package: Path | None = None, config_root: Path | None = None) -> list[str]:
    """Problems with the committed registry against the committed split-file copy (empty: they agree)."""

    package = package or package_root()
    config_root = config_root or default_config_root()
    copies = packaged_split_copies(package)
    if len(copies) != 1:
        return [f"expected exactly one packaged split file under {PACKAGED_DIR}, found {[path.name for path in copies]}"]
    committed = (config_root / EVAL_RESERVED_UNITS_FILE).read_text(encoding="utf-8")
    expected = render_registry(copies[0].read_bytes(), copies[0].name)
    return [] if committed == expected else [f"{EVAL_RESERVED_UNITS_FILE} does not match {copies[0].name}; run sync"]


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    s = sub.add_parser("sync", help="copy the split file into the package and regenerate the registry")
    s.add_argument("--split", type=Path, required=True)
    sub.add_parser("check", help="fail if the committed registry does not match the packaged split file")
    args = parser.parse_args(argv)
    if args.command == "sync":
        print(json.dumps(sync(args.split), ensure_ascii=False, indent=2))
        return 0
    problems = check()
    print(json.dumps({"problems": problems}, ensure_ascii=False))
    return 1 if problems else 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
